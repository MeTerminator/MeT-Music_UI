"""Generate the shared QQ quality catalogue from the backend. No network required."""

import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root.parent / "MeT-Music_Backend/docs/qq-qualities.json"
output = root / "packages/core/src/qq-qualities.generated.ts"
text = "// Generated by scripts/generate-qq-qualities.py from backend docs/qq-qualities.json.\n"
text += (
    "export const qqQualities = "
    + json.dumps(json.loads(source.read_text()), ensure_ascii=False, indent=2)
    + " as const;\n"
)
if "--check" in sys.argv:
    if not output.exists() or output.read_text() != text:
        raise SystemExit(
            "QQ catalogue is stale: python3 scripts/generate-qq-qualities.py"
        )
else:
    output.write_text(text)
